// Song content generator - a reusable little synth + Standard MIDI File
// writer for producing a chart's .wav/.mid pairs from code instead of real
// recordings: square/triangle/bell/bass tones for melodic clips, noise+sine
// drum hits for percussion, all mixed and written as plain 16-bit mono PCM
// WAV, plus (for judged clips) a matching note chart using the engine's
// four fixed lane pitches (c_LaneMidiPitches in src/LaneConfig.h - keep this
// in sync if that ever changes). Deterministic: the noise generator is a
// seeded LCG, so re-running produces byte-identical output.
//
// Not wired into CMakeLists.txt (it has no dependency on the engine at
// all, just the C++ standard library) - compile and run it directly:
//   g++ -O2 -std=c++20 -o song_gen.exe tools/SongGenerator.cpp
//   ./song_gen.exe        (run from the repo root - paths are relative to it)
//
// Everything above main() is the reusable part (WAV/MIDI writers, DSP
// helpers, the Mixer, the reverb, the drum/melodic voice renderers,
// GenerateDrumClip/GenerateMelodicClip/Humanize). main() itself generates
// every code-authored song in one place, each in its own Generate*Song()
// function with its own dir/bpm/note tables - see Content/Byte Blaster (AI
// Slop)/Byte Blaster.chart, Content/Voltage Run (AI Slop)/Voltage Run.chart
// and Content/Quiet Hours/Quiet Hours.chart for the [song]/[clip]/section
// text each function was written to match (those files aren't generated by
// this tool - they're still hand-authored, same as any other chart).
// Keeping all three in one file, instead of overwriting main() per song
// like earlier versions of this file did, is deliberate: an earlier
// rewrite silently lost Voltage Run's original note tables (only the
// rendered .wav/.mid survived in git) - to author a new song without
// erasing the others, add a new Generate*Song() function and call it from
// main() alongside the rest, rather than replacing what's there.
//
// Mix/DSP notes (read this before tweaking levels): GenerateMelodicClip and
// GenerateDrumClip take a targetPeak that normalizes *that one clip* to a
// modest peak, not a hot near-0dBFS master - because a chart's sections
// regularly play several clips at once (see [background]/[break] in any
// .chart file), and this tool has no idea how many will stack on top of
// each other at runtime. Keep targetPeak in the ~0.3-0.6 range (matching
// the headroom real recorded stems in Content/ use - check with a peak/RMS
// tool before assuming a level is fine) rather than normalizing each clip
// toward 1.0 in isolation; the latter is exactly what made the original
// "AI Slop" songs clip and distort once multiple stems summed together.
