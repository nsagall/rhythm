constexpr int c_SampleRate = 44100;
constexpr int c_TicksPerQuarter = 480;
constexpr int c_LaneMidiPitches[4] = {72, 74, 76, 77};

// ---------- WAV writer ----------

void WriteWavMono16(const std::string& path, const std::vector<int16_t>& samples)
{
    std::ofstream f(path, std::ios::binary);
    uint32_t dataBytes = static_cast<uint32_t>(samples.size() * sizeof(int16_t));
    uint32_t riffSize = 36 + dataBytes;
    uint16_t formatTag = 1; // PCM
    uint16_t channels = 1;
    uint32_t sampleRate = c_SampleRate;
    uint16_t bitsPerSample = 16;
    uint16_t blockAlign = channels * bitsPerSample / 8;
    uint32_t byteRate = sampleRate * blockAlign;
    uint32_t fmtSize = 16;

    f.write("RIFF", 4);
    f.write(reinterpret_cast<const char*>(&riffSize), 4);
    f.write("WAVE", 4);
    f.write("fmt ", 4);
    f.write(reinterpret_cast<const char*>(&fmtSize), 4);
    f.write(reinterpret_cast<const char*>(&formatTag), 2);
    f.write(reinterpret_cast<const char*>(&channels), 2);
    f.write(reinterpret_cast<const char*>(&sampleRate), 4);
    f.write(reinterpret_cast<const char*>(&byteRate), 4);
    f.write(reinterpret_cast<const char*>(&blockAlign), 2);
    f.write(reinterpret_cast<const char*>(&bitsPerSample), 2);
    f.write("data", 4);
    f.write(reinterpret_cast<const char*>(&dataBytes), 4);
    f.write(reinterpret_cast<const char*>(samples.data()), dataBytes);
}

// ---------- MIDI writer ----------

void WriteVLQ(std::vector<uint8_t>& out, uint32_t value)
{
    uint8_t buffer[4];
    int count = 0;
    buffer[count++] = static_cast<uint8_t>(value & 0x7F);
    value >>= 7;
    while (value > 0)
    {
        buffer[count++] = static_cast<uint8_t>(value & 0x7F);
        value >>= 7;
    }
    for (int i = count - 1; i >= 0; --i)
    {
        uint8_t b = buffer[i];
        if (i != 0)
        {
            b |= 0x80;
        }
        out.push_back(b);
    }
}

void WriteBE32(std::ofstream& f, uint32_t v)
{
    uint8_t b[4] = {static_cast<uint8_t>(v >> 24), static_cast<uint8_t>(v >> 16), static_cast<uint8_t>(v >> 8),
                     static_cast<uint8_t>(v)};
    f.write(reinterpret_cast<const char*>(b), 4);
}

void WriteBE16(std::ofstream& f, uint16_t v)
{
    uint8_t b[2] = {static_cast<uint8_t>(v >> 8), static_cast<uint8_t>(v)};
    f.write(reinterpret_cast<const char*>(b), 2);
}

struct MidiNote
{
    int startTick = 0;
    int endTick = 0;
    int pitch = 0;
};

void WriteMidiFile(const std::string& path, const std::vector<MidiNote>& notes, int totalTicks)
{
    struct RawEvent
    {
        int tick;
        bool isOn;
        int pitch;
    };
    std::vector<RawEvent> events;
    events.reserve(notes.size() * 2);
    for (const MidiNote& n : notes)
    {
        events.push_back({n.startTick, true, n.pitch});
        events.push_back({n.endTick, false, n.pitch});
    }
    std::stable_sort(events.begin(), events.end(),
                      [](const RawEvent& a, const RawEvent& b)
                      {
                          if (a.tick != b.tick)
                          {
                              return a.tick < b.tick;
                          }
                          // Note-offs before note-ons at the same tick, so a
                          // back-to-back same-pitch/lane repeat never reads
                          // as a zero-length overlap.
                          return !a.isOn && b.isOn;
                      });

    std::vector<uint8_t> track;
    int prevTick = 0;
    for (const RawEvent& e : events)
    {
        WriteVLQ(track, static_cast<uint32_t>(e.tick - prevTick));
        prevTick = e.tick;
        track.push_back(e.isOn ? 0x90 : 0x80);
        track.push_back(static_cast<uint8_t>(e.pitch));
        track.push_back(e.isOn ? 100 : 64);
    }
    // End-of-track meta event, placed at totalTicks (not just the last
    // note's own end) so the pattern's declared length matches the audio's
    // full loop instead of shrinking to whatever the last note happened to
    // end on.
    WriteVLQ(track, static_cast<uint32_t>(std::max(0, totalTicks - prevTick)));
    track.push_back(0xFF);
    track.push_back(0x2F);
    track.push_back(0x00);

    std::ofstream f(path, std::ios::binary);
    f.write("MThd", 4);
    WriteBE32(f, 6);
    WriteBE16(f, 0); // format 0: single track
    WriteBE16(f, 1); // ntrks
    WriteBE16(f, static_cast<uint16_t>(c_TicksPerQuarter));
    f.write("MTrk", 4);
    WriteBE32(f, static_cast<uint32_t>(track.size()));
    f.write(reinterpret_cast<const char*>(track.data()), static_cast<std::streamsize>(track.size()));
}

// ---------- DSP ----------

// Deterministic LCG noise so re-running the generator reproduces byte-
// identical output.
double NoiseSample(uint32_t& state)
{
    state = state * 1664525u + 1013904223u;
    return (static_cast<double>(state) / 4294967295.0) * 2.0 - 1.0;
}

double Square(double phase)
{
    return std::fmod(phase, 1.0) < 0.5 ? 1.0 : -1.0;
}

double Triangle(double phase)
{
    double p = std::fmod(phase, 1.0);
    return p < 0.5 ? (4.0 * p - 1.0) : (3.0 - 4.0 * p);
}

// One-pole low-pass; alpha in (0,1], smaller = darker.
double OnePoleLowPass(double x, double& state, double alpha)
{
    state += alpha * (x - state);
    return state;
}

// tanh soft-knee limiter: transparent below threshold, rounds off peaks
// above it instead of flat-topping them the way a hard clamp does - a
// safety net for the rare transient that pokes over targetPeak, not
// something the normal mix should lean on.
double SoftClip(double x, double threshold = 0.85)
{
    double sign = x < 0.0 ? -1.0 : 1.0;
    double a = std::abs(x);
    if (a <= threshold)
    {
        return x;
    }
    double over = (a - threshold) / (1.0 - threshold);
    double compressed = threshold + (1.0 - threshold) * std::tanh(over);
    return sign * compressed;
}

// ---------- Small Schroeder reverb (mono) ----------
//
// Four parallel feedback combs (each with a damped low-pass in its feedback
// path, so the tail darkens as it decays instead of ringing brightly
// forever) summed and run through two series allpasses to diffuse it into
// a smooth wash rather than discrete echoes. This is the single biggest
// lever for not sounding like a dry, close-mic'd synth demo - real
// recorded stems in Content/ all carry some room/plugin space; the
// original "AI Slop" clips had none at all.
struct CombFilter
{
    std::vector<double> buffer;
    size_t pos = 0;
    double feedback;
    double damp;
    double dampState = 0.0;

    CombFilter(int delaySamples, double feedbackAmt, double dampAmt)
        : buffer(static_cast<size_t>(delaySamples), 0.0), feedback(feedbackAmt), damp(dampAmt)
    {
    }

    double Process(double input)
    {
        double out = buffer[pos];
        dampState = OnePoleLowPass(out, dampState, 1.0 - damp);
        buffer[pos] = input + dampState * feedback;
        pos = (pos + 1) % buffer.size();
        return out;
    }
};

struct AllpassFilter
{
    std::vector<double> buffer;
    size_t pos = 0;
    double feedback;

    AllpassFilter(int delaySamples, double feedbackAmt) : buffer(static_cast<size_t>(delaySamples), 0.0), feedback(feedbackAmt)
    {
    }

    double Process(double input)
    {
        double bufOut = buffer[pos];
        double output = -input + bufOut;
        buffer[pos] = input + bufOut * feedback;
        pos = (pos + 1) % buffer.size();
        return output;
    }
};

// Runs `dry` through the reverb twice back-to-back and keeps only the
// second pass's output, so the tail has already settled into its loop-
// steady-state by the time playback actually starts - the returned buffer
// is exactly dry.size() samples (no trailing tail appended), which matters
// because every clip's duration is load-bearing: ChartClip's loop/advance
// math assumes a clip's audio length exactly matches its authored beat
// length, so we can't just bolt a decay tail onto the end.
std::vector<double> ApplyLoopingReverb(const std::vector<double>& dry, double wetSend, double roomSize)
{
    if (wetSend <= 0.0 || dry.empty())
    {
        return dry;
    }
    static const int c_CombTuningsSamples[4] = {1557, 1617, 1491, 1422};
    static const int c_AllpassTuningsSamples[2] = {556, 441};

    std::vector<CombFilter> combs;
    for (int t : c_CombTuningsSamples)
    {
        combs.emplace_back(t, 0.26 + roomSize * 0.32, 0.25);
    }
    std::vector<AllpassFilter> allpasses;
    for (int t : c_AllpassTuningsSamples)
    {
        allpasses.emplace_back(t, 0.5);
    }

    size_t n = dry.size();
    std::vector<double> wetSecondPass(n);
    for (int pass = 0; pass < 2; ++pass)
    {
        for (size_t i = 0; i < n; ++i)
        {
            double input = dry[i];
            double sum = 0.0;
            for (CombFilter& c : combs)
            {
                sum += c.Process(input);
            }
            sum *= 0.25;
            for (AllpassFilter& a : allpasses)
            {
                sum = a.Process(sum);
            }
            if (pass == 1)
            {
                wetSecondPass[i] = sum;
            }
        }
    }
    std::vector<double> out(n);
    for (size_t i = 0; i < n; ++i)
    {
        out[i] = dry[i] + wetSecondPass[i] * wetSend;
    }
    return out;
}

struct Mixer
{
    std::vector<double> buffer; // -1..1 range, additive

    explicit Mixer(int totalSamples) : buffer(static_cast<size_t>(totalSamples), 0.0)
    {
    }

    void Add(int startSample, const std::vector<double>& voice)
    {
        for (size_t i = 0; i < voice.size(); ++i)
        {
            size_t idx = static_cast<size_t>(startSample) + i;
            if (idx < buffer.size())
            {
                buffer[idx] += voice[i];
            }
        }
    }

    // wetSend 0 disables the reverb entirely (cheap no-op) - see
    // ApplyLoopingReverb's own comment for why this preserves buffer length.
    void ApplyInsertReverb(double wetSend, double roomSize)
    {
        buffer = ApplyLoopingReverb(buffer, wetSend, roomSize);
    }

    // targetPeak should be a headroom-aware level (~0.3-0.6), not close to
    // 1.0 - see this file's top comment. SoftClip is just a safety net for
    // whatever narrow transient still pokes past it.
    std::vector<int16_t> ToPcm16(double targetPeak) const
    {
        double peak = 1e-6;
        for (double v : buffer)
        {
            peak = std::max(peak, std::abs(v));
        }
        double scale = peak > targetPeak ? (targetPeak / peak) : 1.0;
        std::vector<int16_t> out(buffer.size());
        for (size_t i = 0; i < buffer.size(); ++i)
        {
            double v = SoftClip(buffer[i] * scale);
            out[i] = static_cast<int16_t>(std::lround(std::clamp(v, -1.0, 1.0) * 32767.0));
        }
        return out;
    }
};

// ---------- Instrument voices ----------

// Percussive drum hit rendered straight into a fresh vector, added into the
// mixer at the event's own start sample - envelope length is the drum's own
// natural decay, independent of however short the chart's own tap-note
// duration is (a real drum's sound outlasts a quick press/release gesture).
std::vector<double> RenderKick(uint32_t& noiseState)
{
    int n = static_cast<int>(0.20 * c_SampleRate);
    std::vector<double> v(static_cast<size_t>(n));
    for (int i = 0; i < n; ++i)
    {
        double t = i / static_cast<double>(c_SampleRate);
        double freq = 150.0 * std::exp(-t * 28.0) + 48.0; // pitch sweep, high -> low
        double phase = std::fmod(t * freq, 1.0);
        double tone = std::sin(2.0 * 3.14159265358979 * phase);
        double amp = std::exp(-t * 16.0);
        // Softer, shorter click than before (was 0.35 over 4ms) - the
        // original read as a harsh digital tick sitting on top of the kick.
        double click = (t < 0.003) ? NoiseSample(noiseState) * (1.0 - t / 0.003) * 0.18 : 0.0;
        v[static_cast<size_t>(i)] = (tone * amp + click) * 0.9;
    }
    return v;
}

std::vector<double> RenderSnare(uint32_t& noiseState)
{
    int n = static_cast<int>(0.16 * c_SampleRate);
    std::vector<double> v(static_cast<size_t>(n));
    double lpState = 0.0;
    for (int i = 0; i < n; ++i)
    {
        double t = i / static_cast<double>(c_SampleRate);
        double noise = NoiseSample(noiseState);
        lpState = OnePoleLowPass(noise, lpState, 0.5);
        double highPassed = noise - lpState; // crude high-pass: original minus a low-passed copy
        double noiseAmp = std::exp(-t * 24.0);
        double tone = std::sin(2.0 * 3.14159265358979 * 190.0 * t) * std::exp(-t * 30.0);
        v[static_cast<size_t>(i)] = (highPassed * 0.6 * noiseAmp + tone * 0.5) * 0.8;
    }
    return v;
}

std::vector<double> RenderHihat(uint32_t& noiseState)
{
    int n = static_cast<int>(0.06 * c_SampleRate);
    std::vector<double> v(static_cast<size_t>(n));
    double lp1 = 0.0, lp2 = 0.0, lp3 = 0.0;
    for (int i = 0; i < n; ++i)
    {
        double t = i / static_cast<double>(c_SampleRate);
        double noise = NoiseSample(noiseState);
        lp1 = OnePoleLowPass(noise, lp1, 0.35);
        lp2 = OnePoleLowPass(lp1, lp2, 0.35);
        // A third cascaded LP (was two) rounds off the harshest top end a
        // touch more while still leaving plenty of sizzle.
        lp3 = OnePoleLowPass(lp2, lp3, 0.45);
        double highPassed = noise - lp3;
        double amp = std::exp(-t * 55.0);
        v[static_cast<size_t>(i)] = highPassed * amp * 0.5;
    }
    return v;
}

std::vector<double> RenderTom(uint32_t& noiseState)
{
    int n = static_cast<int>(0.18 * c_SampleRate);
    std::vector<double> v(static_cast<size_t>(n));
    for (int i = 0; i < n; ++i)
    {
        double t = i / static_cast<double>(c_SampleRate);
        double freq = 300.0 * std::exp(-t * 14.0) + 130.0;
        double phase = std::fmod(t * freq, 1.0);
        double tone = std::sin(2.0 * 3.14159265358979 * phase);
        double amp = std::exp(-t * 13.0);
        double noise = NoiseSample(noiseState) * 0.08 * std::exp(-t * 40.0);
        v[static_cast<size_t>(i)] = (tone * amp + noise) * 0.85;
    }
    return v;
}

enum class Timbre
{
    Square,
    Triangle,
    Bell,
    // A soft sub-register voice for a bassline: triangle+sine blend (far
    // fewer/weaker harmonics than Square - see RenderMelodicNote), then
    // run through an extra low-pass pass of its own on top of the shared
    // envelope, so it reads as warm low end instead of competing with the
    // lead/arp's own brighter timbres up in the mix.
    Bass,
};

// Melodic note - length follows the chart's own note duration (in
// seconds), giving a short envelope with a bit of release tail so back-to-
// back staccato notes never click. velocity is a linear gain multiplier
// (1.0 = full), used to humanize a performance instead of every note
// hitting identically.
std::vector<double> RenderMelodicNote(double freqHz, double durationSeconds, Timbre timbre, double velocity = 1.0)
{
    double releaseSeconds = (timbre == Timbre::Bell) ? 0.45 : 0.10;
    int n = static_cast<int>((durationSeconds + releaseSeconds) * c_SampleRate);
    n = std::max(n, 8);
    std::vector<double> v(static_cast<size_t>(n));
    double attackSeconds = (timbre == Timbre::Bell) ? 0.015 : 0.006;
    // Sustain plateau well below the old flat 0.85 - at 0.85 a held square/
    // triangle note reads as a constant wall of buzz (crest factor ~1.9,
    // i.e. almost no dynamic shape at all). Bell keeps its own decaying
    // sustain curve below.
    double sustainLevel = (timbre == Timbre::Bell) ? 1.0 : 0.55;
    for (int i = 0; i < n; ++i)
    {
        double t = i / static_cast<double>(c_SampleRate);
        double env;
        if (t < attackSeconds)
        {
            env = (t / attackSeconds) * sustainLevel;
        }
        else if (t < durationSeconds)
        {
            env = (timbre == Timbre::Bell) ? std::exp(-(t - attackSeconds) * 1.2) : sustainLevel;
        }
        else
        {
            double releaseT = t - durationSeconds;
            double heldLevel =
                (timbre == Timbre::Bell) ? std::exp(-(durationSeconds - attackSeconds) * 1.2) : sustainLevel;
            env = heldLevel * std::exp(-releaseT / (releaseSeconds * 0.35));
        }

        double sample = 0.0;
        if (timbre == Timbre::Square)
        {
            sample = Square(t * freqHz) * 0.5;
        }
        else if (timbre == Timbre::Triangle)
        {
            sample = Triangle(t * freqHz) * 0.6;
        }
        else if (timbre == Timbre::Bass)
        {
            sample = (Triangle(t * freqHz) * 0.6 + std::sin(2.0 * 3.14159265358979 * freqHz * t) * 0.4) * 0.6;
        }
        else // Bell
        {
            sample = std::sin(2.0 * 3.14159265358979 * freqHz * t) * 0.5 +
                     std::sin(2.0 * 3.14159265358979 * freqHz * 2.01 * t) * 0.18 +
                     std::sin(2.0 * 3.14159265358979 * freqHz * 3.0 * t) * 0.08;
        }
        v[static_cast<size_t>(i)] = sample * env * velocity;
    }

    if (timbre == Timbre::Square || timbre == Timbre::Triangle)
    {
        // Rounds off the raw oscillator's harshest upper harmonics -
        // Square gets more smoothing than Triangle since it starts with
        // far more high-harmonic content to begin with.
        double state = 0.0;
        double alpha = (timbre == Timbre::Square) ? 0.5 : 0.75;
        for (double& s : v)
        {
            s = OnePoleLowPass(s, state, alpha);
        }
    }
    else if (timbre == Timbre::Bass)
    {
        // A second low-pass pass smooths off whatever edge the
        // triangle+sine blend still has, so it reads as round low end
        // rather than a synth tone that merely happens to be pitched low.
        double state = 0.0;
        for (double& s : v)
        {
            s = OnePoleLowPass(s, state, 0.18);
        }
    }
    return v;
}

// ---------- Clip data model ----------

enum class DrumPart
{
    Kick,
    Snare,
    Hihat,
    Tom,
};

struct DrumHit
{
    double beat;
    int lane; // also selects the part: 0=kick,1=snare,2=hihat,3=tom
    double velocity = 1.0;
};

struct MelodicEvent
{
    double beat;
    double durationBeats;
    int lane;
    double freqHz;
    double velocity = 1.0;
};

// Nudges each event's timing/velocity by a small deterministic amount so a
// programmed pattern doesn't read as perfectly typed-in - real playing
// never lands two notes with identical timing and force. Only ever applied
// to the "audio" event lists, never to chartEvents/chartHits: the judged
// note chart has to stay exactly quantized to what ChartMidi loads, since
// that's what the player is being timed against.
std::vector<MelodicEvent> Humanize(std::vector<MelodicEvent> events, uint32_t seed, double timingJitterBeats,
                                    double velocityJitter)
{
    uint32_t state = seed;
    for (MelodicEvent& e : events)
    {
        e.beat = std::max(0.0, e.beat + NoiseSample(state) * timingJitterBeats);
        e.velocity *= 1.0 + NoiseSample(state) * velocityJitter;
    }
    return events;
}

std::vector<DrumHit> HumanizeDrums(std::vector<DrumHit> hits, uint32_t seed, double timingJitterBeats,
                                    double velocityJitter)
{
    uint32_t state = seed;
    for (DrumHit& h : hits)
    {
        h.beat = std::max(0.0, h.beat + NoiseSample(state) * timingJitterBeats);
        h.velocity *= 1.0 + NoiseSample(state) * velocityJitter;
    }
    return hits;
}

// Renders a drum-pattern clip's audio from audioHits (the "real"
// performance - as busy/musical as sounds good) and, unless
// chartHits is empty, a SEPARATE note chart from chartHits - deliberately
// not the same list. The audio is what the arrangement actually needs to
// sound good; the chart is what the player actually needs to judge, and
// the two don't have to agree on density at all (see GenerateMelodicClip's
// own comment for why this split exists).
//
// targetPeak/reverbSend/roomSize: see this file's top comment on gain
// staging - keep targetPeak well under 1.0 so simultaneous clips (see any
// [background]/[break] section) sum without clipping.
void GenerateDrumClip(const std::string& dir, const std::string& name, const std::vector<DrumHit>& audioHits,
                       const std::vector<DrumHit>& chartHits, double totalBeats, double secondsPerBeat,
                       uint32_t noiseSeed, double targetPeak = 0.55, double reverbSend = 0.0, double roomSize = 0.3)
{
    int totalSamples = static_cast<int>(std::lround(totalBeats * secondsPerBeat * c_SampleRate));
    Mixer mixer(totalSamples);
    uint32_t noiseState = noiseSeed;

    for (const DrumHit& h : audioHits)
    {
        int startSample = static_cast<int>(std::lround(h.beat * secondsPerBeat * c_SampleRate));
        std::vector<double> voice;
        switch (h.lane)
        {
            case 0:
                voice = RenderKick(noiseState);
                break;
            case 1:
                voice = RenderSnare(noiseState);
                break;
            case 2:
                voice = RenderHihat(noiseState);
                break;
            default:
                voice = RenderTom(noiseState);
                break;
        }
        for (double& s : voice)
        {
            s *= h.velocity;
        }
        mixer.Add(startSample, voice);
    }
    mixer.ApplyInsertReverb(reverbSend, roomSize);
    WriteWavMono16(dir + "/" + name + ".wav", mixer.ToPcm16(targetPeak));

    if (!chartHits.empty())
    {
        std::vector<MidiNote> notes;
        for (const DrumHit& h : chartHits)
        {
            int startTick = static_cast<int>(std::lround(h.beat * c_TicksPerQuarter));
            int endTick = startTick + static_cast<int>(std::lround(0.15 * c_TicksPerQuarter));
            notes.push_back({startTick, endTick, c_LaneMidiPitches[h.lane]});
        }
        int totalTicks = static_cast<int>(std::lround(totalBeats * c_TicksPerQuarter));
        WriteMidiFile(dir + "/" + name + ".mid", notes, totalTicks);
        printf("  %s: %d audio hits / %d chart hits, %.2fs, %d ticks\n", name.c_str(), (int)audioHits.size(),
               (int)chartHits.size(), totalBeats * secondsPerBeat, totalTicks);
    }
    else
    {
        printf("  %s: %d audio hits (background, no chart), %.2fs\n", name.c_str(), (int)audioHits.size(),
               totalBeats * secondsPerBeat);
    }
}

// audioEvents drives the actual musical arrangement (the WAV) - as dense
// or intricate as sounds good, e.g. a fast 16th-note arpeggio. chartEvents
// drives the judged note chart, authored independently and typically much
// sparser: a section's clip is picked, at BeginSection, purely by index
// into ChartSong::clips/laneNotes (see GameSession.h) - it never inspects
// the audio at all - so nothing requires the two to have matching density.
// Keeping the chart easy while the audio stays full-arrangement is exactly
// the intended use of that decoupling.
void GenerateMelodicClip(const std::string& dir, const std::string& name, const std::vector<MelodicEvent>& audioEvents,
                          const std::vector<MelodicEvent>& chartEvents, double totalBeats, double secondsPerBeat,
                          Timbre timbre, double targetPeak = 0.42, double reverbSend = 0.12, double roomSize = 0.35)
{
    int totalSamples = static_cast<int>(std::lround(totalBeats * secondsPerBeat * c_SampleRate));
    Mixer mixer(totalSamples);
    for (const MelodicEvent& e : audioEvents)
    {
        int startSample = static_cast<int>(std::lround(e.beat * secondsPerBeat * c_SampleRate));
        std::vector<double> voice = RenderMelodicNote(e.freqHz, e.durationBeats * secondsPerBeat, timbre, e.velocity);
        mixer.Add(startSample, voice);
    }
    mixer.ApplyInsertReverb(reverbSend, roomSize);
    WriteWavMono16(dir + "/" + name + ".wav", mixer.ToPcm16(targetPeak));

    std::vector<MidiNote> notes;
    for (const MelodicEvent& e : chartEvents)
    {
        int startTick = static_cast<int>(std::lround(e.beat * c_TicksPerQuarter));
        int endTick = static_cast<int>(std::lround((e.beat + e.durationBeats) * c_TicksPerQuarter));
        notes.push_back({startTick, endTick, c_LaneMidiPitches[e.lane]});
    }
    int totalTicks = static_cast<int>(std::lround(totalBeats * c_TicksPerQuarter));
    WriteMidiFile(dir + "/" + name + ".mid", notes, totalTicks);
    printf("  %s: %d audio notes / %d chart notes, %.2fs, %d ticks\n", name.c_str(), (int)audioEvents.size(),
           (int)chartEvents.size(), totalBeats * secondsPerBeat, totalTicks);
}

